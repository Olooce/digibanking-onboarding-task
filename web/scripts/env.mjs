// Generates src/env.generated.ts from web/.env (falls back to .env.example).
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = new URL('..', import.meta.url);
const envFile = fileURLToPath(new URL('.env', root));
const exampleFile = fileURLToPath(new URL('.env.example', root));
const outFile = fileURLToPath(new URL('src/env.generated.ts', root));

function parse(text) {
    const vars = {};
    for (const line of text.split(/\r?\n/)) {
        const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
        if (!match || line.trimStart().startsWith('#')) continue;
        vars[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
    }
    return vars;
}

const source = existsSync(envFile) ? envFile : exampleFile;
if (source === exampleFile) console.warn('[env] web/.env not found; using .env.example defaults.');
const fileVars = existsSync(source) ? parse(readFileSync(source, 'utf8')) : {};
const raw = process.env.API_BASE_URL ?? fileVars.API_BASE_URL;

if (!raw) {
    console.error('[env] API_BASE_URL is not set. Copy .env.example to .env and set it.');
    process.exit(1);
}

let url;
try {
    url = new URL(raw);
} catch {
    console.error(`[env] API_BASE_URL is not a valid URL: ${raw}`);
    process.exit(1);
}
if (url.protocol !== 'http:' && url.protocol !== 'https:') {
    console.error(`[env] API_BASE_URL must use http or https: ${raw}`);
    process.exit(1);
}

const apiBase = `${url.origin}${url.pathname.replace(/\/+$/, '')}`;
writeFileSync(outFile, `// Generated by scripts/env.mjs. Do not edit; change web/.env instead.\nexport const API_BASE_URL = ${JSON.stringify(apiBase)};\n`);
console.log(`[env] API_BASE_URL = ${apiBase}`);
